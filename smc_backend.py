def load_data(drive_load_dir,tickers=None):
  # Check if the directory exists
  if not os.path.exists(drive_load_dir):
      print(f"Error: Directory not found at {drive_load_dir}. Please ensure the data was saved correctly.")
  else:
      print(f"Loading data from: {drive_load_dir}")

      # Initialize an empty dictionary to store the loaded data
      loaded_data_multi = {}
      all_files = os.listdir(drive_load_dir)

      if tickers is not None:
        all_files = [file for file in all_files if any(ticker.split('.')[0] in file for ticker in tickers)]

      # Iterate through files in the directory
      for filename in all_files:
          if filename.endswith('.csv'):
              # Extract ticker and interval from the filename
              parts = filename.replace('.csv', '').split('_')
              if len(parts) >= 2:
                  # Reconstruct original ticker (e.g., 'ABB_NS' -> 'ABB.NS')
                  ticker_parts = parts[:-1] # All parts except the last one are for the ticker
                  interval = parts[-1]   # The last part is the interval

                  if len(ticker_parts) == 2: # For tickers like 'ABB_NS'
                      ticker = f"{ticker_parts[0]}.{ticker_parts[1]}"
                  else: # For tickers like 'DMART' or 'ADANIENT'
                      ticker = "_".join(ticker_parts) # Join if there are multiple underscores in ticker name itself, although 'tickers' list seems to have only one dot
                      # A better way might be to store ticker and interval separately during saving, or use regex for more robust parsing

                  filepath = os.path.join(drive_load_dir, filename)
                  try:
                      df = pd.read_csv(filepath, index_col='Date', parse_dates=True)
                      if ticker not in loaded_data_multi:
                          loaded_data_multi[ticker] = {}
                      loaded_data_multi[ticker][interval] = df
                      #print(f"Loaded {ticker} data for interval {interval} from {filename}")
                  except Exception as e:
                      print(f"Error loading {filename}: {e}")

      print("\n--- All data loaded from Google Drive ---")
      return loaded_data_multi

def download_data(ticker, start_date="2023-01-01", end_date=None, intervals=["1d", "1wk", "1mo"]):
    """
    Downloads data for multiple intervals efficiently.
    Returns a dictionary: {interval: dataframe}
    """
    if end_date is None:
        end_date = date.today().strftime("%Y-%m-%d")

    results = {}

    for interval in intervals:
        try:
            # Small sleep to prevent rate limiting if calling in a large loop
            time.sleep(0.2)

            df = yf.download(ticker, start=start_date, end=end_date, interval=interval, progress=False, auto_adjust=True)

            if df.empty:
                print(f"No data found for {ticker} at {interval}")
                continue

            # Flatten multi-level columns if they exist
            if isinstance(df.columns, pd.MultiIndex):
                df.columns = [col[0] for col in df.columns]

            results[interval] = df
            #print(f"Successfully downloaded {ticker} at {interval} interval.")

        except Exception as e:
            print(f"Error downloading {ticker} at {interval}: {e}")

    return results

def resample_data(df, interval='1W'):
    """
    Resamples OHLCV data.
    Intervals: '1W' for Weekly, '1ME' for Monthly
    """
    resampled = df.resample(interval).agg({
        'Open': 'first',
        'High': 'max',
        'Low': 'min',
        'Close': 'last',
        'Volume': 'sum'
    })
    return resampled.dropna()

def infer_bar_frequency(index: pd.DatetimeIndex) -> str:
    """Infer whether the data is daily/weekly/monthly, purely for display -
    all downstream windows are expressed in BARS, not calendar days, so the
    algorithm itself is frequency-agnostic."""
    if len(index) < 3:
        return "unknown"
    median_days = np.median(np.diff(index.values).astype("timedelta64[D]").astype(int))
    if median_days <= 2:
        return "daily"
    if median_days <= 9:
        return "weekly"
    return "monthly"


