def evaluate_strategy_metrics(summary_df):
    """
    Calculates key strategy evaluation metrics from a backtesting summary DataFrame.

    Args:
        summary_df (pd.DataFrame): DataFrame containing trade summaries with
                                   'Trade_PnL', 'Outcome', 'Entry Date', and 'Exit Date' columns.

    Returns:
        dict: A dictionary containing the calculated strategy metrics.
    """
    metrics = {}

    # 1. Net PNL
    metrics['Net PNL'] = summary_df['Trade_PnL'].sum()

    # Winning and Losing Trades
    winning_trades = summary_df[summary_df['Outcome'] == 'Profit']
    losing_trades = summary_df[summary_df['Outcome'] != 'Profit']

    # 2. Average profit per winning trade
    if not winning_trades.empty:
        metrics['Average Profit per Winning Trade'] = winning_trades['Trade_PnL'].mean()
    else:
        metrics['Average Profit per Winning Trade'] = 0.0

    # 3. Average loss per losing trade (as absolute value)
    if not losing_trades.empty:
        metrics['Average Loss per Losing Trade'] = abs(losing_trades['Trade_PnL'].mean())
    else:
        metrics['Average Loss per Losing Trade'] = 0.0

    # 4. Profit factor
    total_gross_profit = winning_trades['Trade_PnL'].sum()
    total_gross_loss = abs(losing_trades['Trade_PnL'].sum())
    if total_gross_loss > 0:
        metrics['Profit Factor'] = total_gross_profit / total_gross_loss
    else:
        metrics['Profit Factor'] = np.inf if total_gross_profit > 0 else 0.0

    # TOTAL ANAL
    total_trades = len(summary_df)
    win_rate = len(winning_trades) / total_trades if total_trades > 0 else 0.0
    loss_rate = 1 - win_rate
    metrics['Win Rate'] = win_rate*100.0
    metrics['Winning Trades'] = len(winning_trades)
    #metrics['Total Loss Rate'] = len(loss_rate)
    #metrics['Losing Trades'] = len(losing_trades)

    # 5. System expectancy
    avg_win = metrics['Average Profit per Winning Trade']
    avg_loss = metrics['Average Loss per Losing Trade']
    metrics['System Expectancy'] = (win_rate * avg_win) - (loss_rate * avg_loss)

    # 6. Expectancy score
    # Calculate days in backtest
    if not summary_df.empty:
        min_date = summary_df['Entry Date'].min()
        max_date = summary_df['Exit Date'].max()
        days_in_backtest = (max_date - min_date).days
    else:
        days_in_backtest = 1 # Avoid division by zero if no trades

    metrics['Expectancy Score'] = metrics['System Expectancy'] * total_trades * 365 / days_in_backtest if days_in_backtest > 0 else 0.0


    # 1. Absolute and Relative Zone Distribution
    demand_trades = summary_df[summary_df['Zone_Type'] == 'Demand']
    supply_trades = summary_df[summary_df['Zone_Type'] == 'Supply']

    dz_count = len(demand_trades)
    sz_count = len(supply_trades)

    metrics['Total Trades'] = total_trades
    metrics['Demand Zones'] = dz_count
    metrics['Supply Zones'] = sz_count

    # NEW: Global Profitability by Zone
    dz_wins = len(demand_trades[demand_trades['Outcome'] == 'Profit'])
    sz_wins = len(supply_trades[supply_trades['Outcome'] == 'Profit'])

    metrics['Profitable Demand Zones'] = dz_wins
    metrics['Profitable Supply Zones'] = sz_wins

    # 2. Timing Analysis
    summary_df['Entry Date'] = pd.to_datetime(summary_df['Entry Date'])
    summary_df['Date Created'] = pd.to_datetime(summary_df['Date Created'])
    summary_df['Exit Date'] = pd.to_datetime(summary_df['Exit Date'])

    summary_df['Time_Creation_to_Entry'] = (summary_df['Entry Date'] - summary_df['Date Created']).dt.days
    summary_df['Time_Entry_to_Exit'] = (summary_df['Exit Date'] - summary_df['Entry Date']).dt.days

    metrics['Avg Time Creation_Entry'] = summary_df['Time_Creation_to_Entry'].mean()

    profitable = summary_df[summary_df['Outcome'] == 'Profit']
    losing = summary_df[summary_df['Outcome'] == 'Stop Loss']


    metrics['Avg Hold Time (Profitable)'] = profitable['Time_Entry_to_Exit'].mean()
    metrics['Avg Hold Time (Losing)'] = losing['Time_Entry_to_Exit'].mean()
    avg_pierce = summary_df['Piercing_Depth'].mean() * 100
    metrics['Avg Piercing %'] = avg_pierce
    metrics['Avg PnL'] = summary_df['Trade_PnL'].mean()

    return metrics

"""### Global Strategy Composite Score
Applying the same logic to the overall portfolio performance to get a single baseline number for the strategy.
"""

def calculate_composite_score(row):
    """
    Calculates a single score from 0-100 based on multiple performance metrics.
    Weights:
    - Profit Factor: 35%
    - Expectancy: 25%
    - Win Rate: 20%
    - Efficiency (Days to Entry / Hold): 20%
    """
    #try:
        # Normalize Profit Factor (Cap at 5 for scoring purposes)
    pf_score = min(row['Profit Factor'] / 3.0, 1.0) * 35

    # Expectancy Score (Normalized against initial risk/100)
    exp_score = min(max(row['System Expectancy'] / 50.0, 0), 1.0) * 25

    # Win Rate
    wr_score = (row['Win Rate'] / 100.0) * 20

    # Efficiency Score (Inverse of Days to Entry - lower is better)
    # We assume > 60 days is 'slow'
    eff_score = max(0, (1 - (row['Avg Time Creation_Entry'] / 60.0))) * 20
    #print(pf_score,exp_score,wr_score,eff_score)

    total_score = pf_score + exp_score + wr_score + eff_score
    return round(total_score, 2)
