# 5. OPTIONAL: GAUSSIAN HMM CROSS-CHECK
# --------------------------------------------------------------------------- #
def hmm_cross_check(returns: pd.Series, n_states: int = 3) -> str | None:
    """Independent second opinion: 3-state Gaussian HMM on log returns,
    states relabeled by fitted mean return (low->Bearish, mid->Sideways,
    high->Bullish). Returns None if hmmlearn isn't installed or fit fails."""
    if not _HMM_AVAILABLE:
        return None
    try:
        X = returns.dropna().values.reshape(-1, 1)
        if len(X) < 60:
            return None
        model = GaussianHMM(n_components=n_states, covariance_type="diag",
                             n_iter=200, random_state=42)
        model.fit(X)
        hidden_states = model.predict(X)
        order = np.argsort(model.means_.flatten())
        label_map = {order[0]: "Bearish", order[1]: "Sideways", order[2]: "Bullish"}
        return label_map[hidden_states[-1]]
    except Exception:
        return None

