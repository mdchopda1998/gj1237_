def calculate_true_range(df):
  """Calculates the True Range (TR) for a given DataFrame."""
  high_series = df['High']
  low_series = df['Low']
  close_series = df['Close']
  prev_close = close_series.shift(1)

  range1 = high_series - low_series
  range2 = abs(high_series - prev_close)
  range3 = abs(low_series - prev_close)

  df['TR'] = pd.DataFrame({'range1': range1, 'range2': range2, 'range3': range3}).max(axis=1)
  return df

def calculate_atr(df, period=14):
    """Calculates the Average True Range (ATR) using EMA of TR."""
    df['ATR'] = df['TR'].ewm(span=period, adjust=False).mean()
    return df

def classify_candles(df,ratio):
    tr = df['TR']
    atr = df['ATR']
    body_size = df['Close'] - df['Open']

    # Identify candle types
    df['Is_Exciting'] = (tr / atr > ratio['Exciting']['TR_ATR']) & ((body_size.abs() / tr) > ratio['Exciting']['BS_TR'])
    df['Is_Base'] = (tr / atr < ratio['Base']['TR_ATR']) & ((body_size.abs() / tr) < ratio['Base']['BS_TR'])
    df['Is_Explosive'] = (tr / atr > ratio['Explosive']['TR_ATR']) & ((body_size.abs() / tr) > ratio['Explosive']['BS_TR'])

    # df['Is_Exciting'] = df['Is_Exciting'] & ~df['Is_Explosive']


    return df

def compute_gap_flags(df: pd.DataFrame,gap_threshold=1.0) -> pd.Series:
    """Flags candles whose opening gap vs prior close exceeds a multiple of ATR."""
    prev_close = df['Close'].shift(1)
    gap = (df['Open'] - prev_close).abs()
    gap_atr_multiple = gap / df['ATR'].replace(0, np.nan)
    df['Gapped'] = gap_atr_multiple > gap_threshold
    return df

def compute_volume_zscore(df: pd.DataFrame, lookback: int) -> pd.Series:
    """Rolling z-score of volume -- flags abnormally thin/illiquid trading."""
    if 'Volume' not in df.columns:
        return pd.Series(np.nan, index=df.index)
    roll_mean = df['Volume'].rolling(lookback).mean()
    roll_std = df['Volume'].rolling(lookback).std().replace(0, np.nan)
    Volume_Zscore = (df['Volume'] - roll_mean) / roll_std
    df['High_Volume'] = Volume_Zscore > 1.5

    return df

def compute_choppiness_index(df: pd.DataFrame, period: int,chop_indx: float) -> pd.Series:
    """Choppiness Index (0-100). High = sideways/choppy, Low = trending."""
    high_max = df['High'].rolling(period).max()
    low_min = df['Low'].rolling(period).min()
    tr_sum = df['TR'].rolling(period).sum()
    span = (high_max - low_min).replace(0, np.nan)
    choppiness = 100 * np.log10(tr_sum / span) / np.log10(period)
    # df['Choppiness'] = choppiness > chop_indx
    df['Trending'] = choppiness < chop_indx
    return df

def detect_swing_points(df: pd.DataFrame, lookback: int) -> pd.DataFrame:
    """
    Fractal-style swing high/low detection used by BOS / OB / Sweep logic.

    NOTE ON CAUSALITY: a fractal swing at bar i is only *confirmed* once we've
    seen `lookback` bars after it (the centered window needs the right-hand
    side to know bar i was a local extreme). `Swing_High`/`Swing_Low` below
    are therefore NOT safe to use directly at their own index -- use
    `get_confirmed_swing_levels()` for any decision made "as of" bar i, which
    correctly delays the signal until it would actually have been known.
    """
    df['Swing_High'] = df['High'] == df['High'].rolling(2 * lookback + 1, center=True).max()
    df['Swing_Low'] = df['Low'] == df['Low'].rolling(2 * lookback + 1, center=True).min()
    return df

def get_confirmed_swing_levels(df: pd.DataFrame, lookback: int):
    """
    Returns (last_swing_high, last_swing_low) as they would have been *knowable*
    at each bar -- i.e. with the `lookback` bars of look-ahead baked into
    `detect_swing_points`'s centered window removed.

    Bug fixed: the previous version shifted the raw (centered, non-causal)
    Swing_High/Swing_Low flags by only 1 bar before use in BOS/OB/Sweep
    detection. Since confirming a swing at bar i requires seeing bars up to
    i + lookback, a shift of 1 leaked up to (lookback - 1) bars of future
    information into every downstream signal -- a classic repainting bug that
    silently inflates backtest performance. Shifting by (lookback + 1) instead
    ensures the swing level used at bar i was fully confirmed by bar i - 1.
    """
    confirm_shift = lookback + 1
    last_swing_high = df['High'].where(df['Swing_High']).ffill().shift(confirm_shift)
    last_swing_low = df['Low'].where(df['Swing_Low']).ffill().shift(confirm_shift)
    return last_swing_high, last_swing_low


def compute_bos_flags_n_liquidity_sweep(df: pd.DataFrame, swing_lookback,sweep_wick_ratio) -> pd.DataFrame:
    """Break of Structure: close beyond the most recent *confirmed* swing high/low."""
    last_swing_high, last_swing_low = get_confirmed_swing_levels(df, swing_lookback)
    df['BOS_Bull'] = df['Close'] > last_swing_high
    df['BOS_Bear'] = df['Close'] < last_swing_low

    """Liquidity Sweep / stop-hunt: wick beyond a swing high/low, closes back inside."""
    candle_range = (df['High'] - df['Low']).replace(0, np.nan)
    upper_wick = df['High'] - df[['Open', 'Close']].max(axis=1)
    lower_wick = df[['Open', 'Close']].min(axis=1) - df['Low']

    df['Sweep_High'] = (df['High'] > last_swing_high) & \
                        (df['Close'] < last_swing_high) & \
                        ((upper_wick / candle_range) > sweep_wick_ratio)

    df['Sweep_Low'] = (df['Low'] < last_swing_low) & \
                       (df['Close'] > last_swing_low) & \
                       ((lower_wick / candle_range) > sweep_wick_ratio)

    return df


def detect_order_blocks(df: pd.DataFrame, require_bos_for_order_block=0) -> pd.DataFrame:
    """
    Order Block (SMC): last opposite-colored candle immediately before an
    impulsive move that produces a Break of Structure.
    """
    is_down = df['Close'] < df['Open']
    is_up = df['Close'] > df['Open']

    bull_ob = is_down.shift(1) & df['BOS_Bull']
    bear_ob = is_up.shift(1) & df['BOS_Bear']

    if require_bos_for_order_block:
        df['Bullish_OB'] = bull_ob
        df['Bearish_OB'] = bear_ob
    else:
        df['Bullish_OB'] = is_down.shift(1) & df['Is_Explosive'] & (df['Close'] > df['Open'])
        df['Bearish_OB'] = is_up.shift(1) & df['Is_Explosive'] & (df['Close'] < df['Open'])

    return df

def identify_zones(df, ratio):
    """Calculates indicators and identifies potential DZone/SZone locations, including continuous zones."""
    df = calculate_true_range(df.copy()) # Adding TR
    df = calculate_atr(df)               # Adding ATR
    df = classify_candles(df,ratio)      # Adding Is_base, Is_Exciting, Is_Explosive to the Df
    df = compute_gap_flags(df,gap_threshold=0.5)           # Adding Gap to the Df
    df = compute_volume_zscore(df, lookback=22) # 1 month  # Adding High_Volume
    df = compute_choppiness_index(df,period=22,chop_indx=38.2)  # Chopiness , Trending < 38.2 < AmbiguousTransitioning < 61.8 < ChopplySideways
    df = detect_swing_points(df, lookback=5) # Adding Swing_High , Swing_Low
    df = compute_bos_flags_n_liquidity_sweep(df, swing_lookback = 22,
                                             sweep_wick_ratio= 3) # Adding BOS_Bull , BOS_Bear, Sweep_High, Sweep_Low # Unclear how BOS will work in Contnuous zones
    df = detect_order_blocks(df,require_bos_for_order_block=0) # Adding Bullish_OB, Bearish_OB


    df['date'] = df.index.strftime('%Y-%m-%d')

    # Basic Pattern: Candle[idx-2] (Exciting) -> Candle[idx-1] (Base) -> Candle[idx] (Explosive)
    df['Zone_Created'] = df['Is_Exciting'].shift(2) & df['Is_Base'].shift(1) & df['Is_Explosive']

    df['Is Continuous'] = False
    df['Is Demand'] = False

    df['Proximal'] = np.nan
    df['Distal'] = np.nan
    df['Target'] = np.nan

    # Demand Zones (Reversal: Drop-Base-Rally | Continuous: Rally-Base-Rally)
    cond_rev_d  = (df['Close'].shift(2) < df['Open'].shift(2)) & (df['Close'] > df['Open'])
    cond_cont_d = (df['Close'].shift(2) > df['Open'].shift(2)) & (df['Close'] > df['Open'])

    # Supply Zones (Reversal: Rally-Base-Drop | Continuous: Drop-Base-Drop)
    cond_rev_s  = (df['Close'].shift(2) > df['Open'].shift(2)) & (df['Close'] < df['Open'])
    cond_cont_s = (df['Close'].shift(2) < df['Open'].shift(2)) & (df['Close'] < df['Open'])

    d_mask = df['Zone_Created'] & (cond_cont_d | cond_rev_d)
    s_mask = df['Zone_Created'] & (cond_rev_s | cond_cont_s)

    df.loc[d_mask,'Is Demand'] = True
    df.loc[df['Zone_Created'] & (cond_cont_d | cond_cont_s),'Is Continuous'] = True

    # Calculate level series for entire DF first to avoid index mismatch
    d_prox_series = df[['Open','Close']].shift(1).max(axis=1)
    d_dist_base = df['Low'].shift(1)
    d_dist_rev = df['Low'].rolling(window=3, min_periods=1).min()

    s_prox_series = df[['Open','Close']].shift(1).min(axis=1)
    s_dist_base = df['High'].shift(1)
    s_dist_rev = df['High'].rolling(window=3, min_periods=1).max()

    # Apply Demand calculations
    if d_mask.any():
        df.loc[d_mask, 'Proximal'] = d_prox_series[d_mask]
        df.loc[d_mask, 'Distal'] = np.where(df.loc[d_mask, 'Is_Continuous'], d_dist_base[d_mask], d_dist_rev[d_mask])

    # Apply Supply calculations
    if s_mask.any():
        df.loc[s_mask, 'Proximal'] = s_prox_series[s_mask]
        # Access values from series using the mask to ensure alignment
        df.loc[s_mask, 'Distal'] = np.where(df.loc[s_mask, 'Is_Continuous'], s_dist_base[s_mask], s_dist_rev[s_mask])

    # Target calculation
    df['Target'] = df['Proximal'] + 2 * (df['Proximal'] - df['Distal'])

    return df

def identity_zones_with_multibase(df,ratio,max_base_candles=10):

  """Calculates indicators and identifies potential DZone/SZone locations, including continuous zones."""
  df = calculate_true_range(df.copy()) # Adding TR
  df = calculate_atr(df)               # Adding ATR
  df = classify_candles(df,ratio)      # Adding Is_base, Is_Exciting, Is_Explosive to the Df
  df = compute_gap_flags(df,gap_threshold=0.5)           # Adding Gap to the Df
  df = compute_volume_zscore(df, lookback=22) # 1 month  # Adding High_Volume
  df = compute_choppiness_index(df,period=22,chop_indx=38.2)  # Chopiness , Trending < 38.2 < AmbiguousTransitioning < 61.8 < ChopplySideways
  df = detect_swing_points(df, lookback=5) # Adding Swing_High , Swing_Low
  df = compute_bos_flags_n_liquidity_sweep(df, swing_lookback = 22,
                                            sweep_wick_ratio= 3) # Adding BOS_Bull , BOS_Bear, Sweep_High, Sweep_Low # Unclear how BOS will work in Contnuous zones
  df = detect_order_blocks(df,require_bos_for_order_block=0) # Adding Bullish_OB, Bearish_OB

  n                         = len(df)
  is_exc,is_base,is_exp     = df['Is_Exciting'],df['Is_Base'],df['Is_Explosive']
  opens,closes              = df['Open'].values,df['Close'].values
  highs,lows                = df['High'].values,df['Low'].values

  zone_created              = np.zeros(n,dtype=bool)
  base_len                  = np.zeros(n,dtype=int)
  leg_in_idx                = np.full(n,-1,dtype=int)
  base_start_idx            = np.full(n,-1,dtype=int)
  base_end_idx              = np.full(n,-1,dtype=int)

  for i in range(2,n):
    if not is_exp.iloc[i]:
      continue

    j,cnt = i-1,0
    while j>=0 and is_base.iloc[j] and cnt<max_base_candles:
      cnt += 1
      j -= 1

    if cnt>=1 and j>=0 and is_exc.iloc[j]:
      zone_created[i] = True
      base_len[i] = cnt
      leg_in_idx[i] = j
      base_start_idx[i] = j+1
      base_end_idx[i] = i-1

  # df['date']            = df.index.strftime('%Y-%m-%d')
  df['Zone_Created']    = zone_created
  df['Base Count']     = base_len
  df['Leg_In_Idx']      = leg_in_idx
  df['Base_Start_Idx']  = base_start_idx
  df['Base_End_Idx']    = base_end_idx
  df['Is Continuous']   = False
  df['Is Demand']       = False
  df['Proximal']        = np.nan
  df['Distal']          = np.nan

  zone_indices = np.where(zone_created)[0]
  for i in zone_indices:
    li,bs,be = leg_in_idx[i],base_start_idx[i],base_end_idx[i]
    leg_in_bull  = closes[li]  > opens[li]
    leg_out_bull = closes[i]  > opens[i]

    is_demand = leg_out_bull
    is_continuous = (leg_in_bull == leg_out_bull)

    base_top = np.maximum(opens[bs:be+1],closes[bs:be+1])
    base_bot = np.minimum(opens[bs:be+1],closes[bs:be+1])
    prox,dist = base_top.max(),base_bot.min()

    if is_demand:
      proximal = base_top.max()
      distal = lows[bs:be+2].min()
      # distal = lows[bs:be+1].min() if is_continuous else lows[bs:be + 2].min()
    else:
      proximal = base_bot.min()
      distal = highs[bs:be+2].max()
      # distal = highs[bs:be+1].max() if is_continuous else highs[bs:be + 2].max()

    df.at[df.index[i], 'Is Demand'] = is_demand
    df.at[df.index[i], 'Is Continuous'] = is_continuous
    df.at[df.index[i], 'Proximal'] = proximal
    df.at[df.index[i], 'Distal'] = distal

  risk = df['Proximal'] - df['Distal']
  df['Target'] = df['Proximal'] + 2 * risk

  return df

def check_refined_htf_support(daily_row, htf_df, creation_date):
    """
    Checks for HTF support with two conditions:
    1. HTF Proximal is within 10% of Daily Distal.
    2. HTF zone has not been breached (price < distal for demand) before daily creation.
    """
    is_demand = daily_row['Is Demand']
    daily_dist = daily_row['Distal']

    # Filter HTF zones of same type created before or on the daily creation date
    valid_htf_zones = htf_df[(htf_df.index <= creation_date) &
                             (htf_df['Zone_Created'] == True) &
                             (htf_df['Is Demand'] == is_demand)]

    if valid_htf_zones.empty:
        return False

    for h_idx, h_row in valid_htf_zones[::-1].iterrows():
        h_prox = h_row['Proximal']
        h_dist = h_row['Distal']

        # 1. Proximity Check: HTF Proximal within 10% of Daily Distal
        proximity_diff = abs(daily_dist - h_prox) / h_prox
        flg1 = proximity_diff <= 0.10
        flg2 = (is_demand and h_dist <= daily_dist) or (not is_demand and h_dist >= daily_dist)

        if flg1 and flg2:
            # 2. Breach Check: Has price breached HTF Distal since HTF creation until Daily creation?
            # For Demand: Breach if Low < HTF Distal. For Supply: Breach if High > HTF Distal.
            period_data = htf_df.loc[h_idx : creation_date]

            if is_demand:
                breached = (period_data['Low'] < h_dist).any()
            else:
                breached = (period_data['High'] > h_dist).any()

            if not breached:
                htf_df.loc[h_idx,'Support'] = True
                return True # Found at least one valid supporting HTF zone

    return False

def calculate_trade_score(ticker,df, weekly_df=None, monthly_df=None, nifty_1d_df=None, nifty_1wk_df=None, nifty_1mo_df=None):
    """Calculates a score for each zone based on Freshness, Strength, Base Count, Weekly Trend, and HTF Support."""
    # Initialize columns
    df_ts = df[df['Zone_Created'] == True].copy()

    df_ts['Freshness'] = False
    df_ts['Strength'] = 0
    df_ts['Gapped'] = False
    df_ts['High Volume'] = False
    df_ts['Trending'] = False
    df_ts['Swing Point'] = False
    df_ts['BOS'] = False
    df_ts['OB'] = False
    df_ts['Sweep'] = False
    df_ts['Trend Support'] = False
    df_ts['ITF Support'] = False
    df_ts['HTF Support'] = False
    df_ts['N_LTF Support'] = False
    df_ts['N_ITF Support'] = False
    df_ts['N_HTF Support'] = False
    # df_ts['HTF_Support_w'] = False
    # df_ts['Nifty_1d_Support'] = False # New column for Nifty 50 daily support
    # df_ts['Nifty_1wk_Support'] = False # New column for Nifty 50 weekly support
    # df_ts['Nifty_1mo_Support'] = False # New column for Nifty 50 monthly support

    df_ts = df_ts.drop(columns=['Close', 'High', 'Low', 'Open', 'Volume', 'TR', 'ATR', 'Is_Exciting',
                                'Is_Base','Is_Explosive','Zone_Created','Proximal','Distal',
                                'Target','Swing_High','Swing_Low','BOS_Bull', 'BOS_Bear','High_Volume',
                                'Sweep_High', 'Sweep_Low', 'Bullish_OB', 'Bearish_OB',
                                'Leg_In_Idx', 'Base_Start_Idx', 'Base_End_Idx'])

    # Insert ticker as first column
    df_ts.insert(0, 'Ticker', ticker)

    if weekly_df is not None and not weekly_df.empty:
      # weekly_df = determine_market_trend(weekly_df, fast_period = 20, slow_period = 50)
      weekly_df = determine_market_trend(weekly_df, window=52)

    # Identify where zones were created (The Leg-out candle)
    zone_indices = np.where(df['Zone_Created'] == True)[0]

    for ind,idx in enumerate(zone_indices):
        if idx >= len(df):
            continue

        row = df.iloc[idx]
        prox, dist = row['Proximal'], row['Distal']
        if pd.isna(prox) or pd.isna(dist):
            continue

        is_demand = row['Is Demand']
        creation_date = df.index[idx]

        # --- 1. Freshness Logic ---
        future_data = df.iloc[idx+1:]
        if not future_data.empty:
            if is_demand:
                touched = (future_data['Low'] <= prox).any()
            else:
                touched = (future_data['High'] >= prox).any()
            df_ts.at[df.index[idx], 'Freshness'] = False if touched else True
        else:
            df_ts.at[df.index[idx], 'Freshness'] = True

        # --- 2. Strength ---
        strength_count = 0
        for i in range(idx, len(df)):
            if df.iloc[i]['Is_Exciting'] or df.iloc[i]['Is_Explosive']:
                strength_count += 1
            else:
                break
        df_ts.at[df.index[idx], 'Strength'] = strength_count

        # --- 3. Number of Base Candles ---
        base_count = 0
        for i in range(idx-1, -1, -1):
            if df.iloc[i]['Is_Base']:
                base_count += 1
            else:
                break
        df_ts.at[df.index[idx], 'Base Count'] = base_count

        # --- 3a. Gap Logic ---
        # flg = df.iloc[idx-2:idx+1]['Gapped'].any()
        flg = df.iloc[idx-2:idx+strength_count]['Gapped'].any()
        df_ts.at[df.index[idx], 'Gapped'] = flg

        # --- 3b. Volume Z Score ---
        # flg = df.iloc[idx-2:idx+1]['High_Volume'].any()
        flg = df.iloc[idx-2:idx+strength_count]['High_Volume'].any()
        df_ts.at[df.index[idx], 'High Volume'] = flg

        # --- 3c. Choppiness Index ---
        # flg = df.iloc[idx-2:idx+1]['Trending'].any()
        flg = df.iloc[idx-2:idx+strength_count]['Trending'].any()
        df_ts.at[df.index[idx], 'Trending'] = flg

        # --- 3d. Swing High/Low ---
        flg1 = df.iloc[idx-2:idx+strength_count]['Swing_High'].any()
        flg2 = df.iloc[idx-2:idx+strength_count]['Swing_Low'].any()
        flg = flg1 or flg2
        df_ts.at[df.index[idx], 'Swing Point'] = flg

        # --- 3d. BOS_Bull / BOS_Bear ---
        if is_demand:
          flg = df.iloc[idx-2:idx+strength_count]['BOS_Bull'].any()
        else:
          flg = df.iloc[idx-2:idx+strength_count]['BOS_Bear'].any()
        df_ts.at[df.index[idx], 'BOS'] = flg

        # --- 3e. Sweep High / Sweeep Low ---
        if is_demand:
          flg = df.iloc[idx-2:idx+strength_count]['Sweep_High'].any()
        else:
          flg = df.iloc[idx-2:idx+strength_count]['Sweep_Low'].any()
        df_ts.at[df.index[idx], 'Sweep'] = flg

        # --- 3f. Bullish_OB / Bearish_OB ---
        flg = df.iloc[idx]['Bullish_OB'] if is_demand else df.iloc[idx]['Bearish_OB']
        df_ts.at[df.index[idx], 'OB'] = flg

        # --- 4a. Weekly Timeframe Intermediate TF Support and Trend Favour ---
        if weekly_df is not None and not weekly_df.empty:
          df_ts.at[df.index[idx], 'ITF Support'] = check_refined_htf_support(row, weekly_df, creation_date)

          available_weekly_dates = weekly_df.index[weekly_df.index <= creation_date]
          if not available_weekly_dates.empty:
            last_weekly_date = available_weekly_dates[-1]
            w_trend = weekly_df.at[last_weekly_date, 'Trend']
            if (is_demand and (w_trend==1)) or (not is_demand and (w_trend==-1)):
              df.at[df.index[idx], 'Trend Support'] = True


        # --- 4b. Monthly Timeframe Higher TF Support ---
        if monthly_df is not None and not monthly_df.empty:
          df_ts.at[df.index[idx], 'HTF Support'] = check_refined_htf_support(row, monthly_df, creation_date)

        # --- 4c. Nifty 50 Support (Daily Overlap) ---
        if nifty_1d_df is not None and not nifty_1d_df.empty:
          df_ts.at[df.index[idx], 'N_LTF Support'] = check_refined_htf_support(row, nifty_1d_df, creation_date)

        # --- 4d. Nifty 50 Support (Weekly Overlap) ---
        if nifty_1wk_df is not None and not nifty_1wk_df.empty:
          df_ts.at[df.index[idx], 'N_ITF Support'] = check_refined_htf_support(row, nifty_1wk_df, creation_date)

        # --- 4e. Nifty 50 Support (Monthly Overlap) ---
        if nifty_1mo_df is not None and not nifty_1mo_df.empty:
          df_ts.at[df.index[idx], 'N_HTF Support'] = check_refined_htf_support(row, nifty_1mo_df, creation_date)
    return df_ts,weekly_df

def backtest_zones(ticker, df,realistic_fills=True):
    """Simulates trades for the identified valid zones."""
    zone_created  = df['Zone_Created'] == True
    df_bt         = pd.DataFrame(index=df[zone_created].index)
    df_bt         = df_bt.rename({'date':'Date Created'})

    df_bt['Ticker'] = ticker
    df_bt['Entry Date'] = pd.NaT
    df_bt['Exit Date'] = pd.NaT
    df_bt['Entry Price'] = np.nan
    df_bt['Exit Price'] = np.nan
    df_bt['Outcome'] = ''
    df_bt['P/L'] = np.nan
    df_bt['R-Multiple'] = np.nan
    df_bt['Proximal'] = np.nan
    df_bt['Distal'] = np.nan
    df_bt['Target'] = np.nan
    df_bt['Piercing_Depth'] = np.nan

    zone_indices  = np.where(zone_created)[0]
    for i,ind in enumerate(zone_indices):
        zone = df.iloc[ind]

        df_test = df.iloc[ind+1:]
        if df_test.empty:
            df_bt.at[df.index[ind], 'Outcome'] = 'No Entry'
            continue

        is_demand           = zone['Is Demand']
        prox, dist, tar     = zone['Proximal'], zone['Distal'], zone['Target']
        risk                = abs(prox - dist)
        if risk == 0:
          df_bt.at[df.index[ind], 'Outcome'] = 'Proximal == Distal'
          continue

        entry_cond = (df_test['Open'] <= prox) | (df_test['Low'] <= prox) if is_demand else (df_test['Open'] >= prox) | (df_test['High'] >= prox)

        entry_idx_rel = np.where(entry_cond)[0]
        if entry_idx_rel.size == 0:
          df_bt.at[df.index[ind], 'Outcome'] = 'No Entry'
          continue

        entry_idx = ind + 1 + entry_idx_rel[0]
        entry_candle = df.iloc[entry_idx]
        open_px = entry_candle['Open']
        close_px = entry_candle['Close']

        if realistic_fills:
          entry_price = min(open_px,prox) if is_demand else max(close_px,prox)
        else:
          entry_price = prox

        df_after              = df.iloc[entry_idx:]
        tar_c                 = (df_after['High'] >= tar) if is_demand else (df_after['Low'] <= tar)
        sl_c                  = (df_after['Low'] <= dist) if is_demand else (df_after['High'] >= dist)
        itar, isl             = np.where(tar_c)[0], np.where(sl_c)[0]
        itar_idx              = entry_idx + itar[0] if itar.size > 0 else np.inf
        isl_idx               = entry_idx + isl[0] if isl.size > 0 else np.inf

        if np.isinf(itar_idx) and np.isinf(isl_idx):
            exit_idx, exit_price, outcome = len(df)-1, df['Close'].iloc[-1], "No Exit (Open)"
        elif isl_idx <= itar_idx:
            exit_idx, exit_price, outcome = isl_idx, dist, "Stop Loss"

            exit_candle_open = df.iloc[exit_idx]['Open']
            if is_demand & (exit_candle_open < exit_price): # To handle gapped entry/ gapped exit
                exit_price = exit_candle_open
            if (not is_demand) & (exit_candle_open > exit_price): # To handle gapped entry/ gapped exit
                exit_price = exit_candle_open
        else:
            exit_idx, exit_price, outcome = itar_idx, tar, "Profit"

        pnl = (exit_price - entry_price) if is_demand else (entry_price - exit_price)
        if pnl == 0.0:
          outcome = 'Invalidated (Gap Through Zone)'

        if outcome == "Stop Loss":
          pnl = -abs(pnl)

        if outcome == "Profit":
          #print(ind,entry_idx,exit_idx,df.shape)
          trade_data = df.iloc[entry_idx:exit_idx+1]
          if is_demand:
              worst_price = trade_data['Low'].min()
              pierce = (prox - worst_price) / risk
          else:
              worst_price = trade_data['High'].max()
              pierce = (worst_price - prox) / risk
          piercing_depth = max(0, min(1, pierce))
          df_bt.at[df.index[ind], 'Piercing_Depth'] = round(piercing_depth, 2)

        df_bt.at[df.index[ind], 'Entry Date']   = df.index[entry_idx]
        df_bt.at[df.index[ind], 'Exit Date']    = df.index[exit_idx]
        df_bt.at[df.index[ind], 'Entry Price']  = round(entry_price, 2)
        df_bt.at[df.index[ind], 'Exit Price']   = round(exit_price, 2)
        df_bt.at[df.index[ind], 'Outcome']      = outcome
        df_bt.at[df.index[ind], 'P/L']          = round(pnl, 2)
        df_bt.at[df.index[ind], 'R-Multiple']   = round(pnl/risk, 2)
        df_bt.at[df.index[ind], 'Proximal']     = round(prox, 2)
        df_bt.at[df.index[ind], 'Distal']       = round(dist, 2)
        df_bt.at[df.index[ind], 'Target']       = round(tar, 2)
    return df_bt

def run_risk_management_simulation(df_bt, initial_capital, risk_percentage_per_trade):
    """
    Applies risk management rules to a summary DataFrame of trades, accounting for sequential trades.

    Args:
        summary_df (pd.DataFrame): DataFrame containing trade summaries with 'Entry Date', 'Exit Date', 'Proximal', 'Distal', 'R-Multiple' columns.
        initial_capital (float): The starting capital for the simulation.
        risk_percentage_per_trade (float): The percentage of capital risked per trade (e.g., 0.01 for 1%).

    Returns:
        pd.DataFrame: The summary_df with added risk management columns.
    """
    valid_outcome = (df_bt['Outcome'] == 'Profit') | (df_bt['Outcome'] == 'Stop Loss')
    df_rm         = df_bt[valid_outcome].copy()

    # Initialize Capital and other columns with float dtype
    df_rm['Capital_At_Entry'] = np.float64(initial_capital)
    df_rm['Risk_Amount_Per_Trade'] = np.float64(0.0)
    df_rm['Quantity'] = np.float64(0.0) # Quantity can be float before casting to int
    df_rm['Trade_PnL'] = np.float64(0.0) # To store the actual profit/loss for the trade based on quantity
    df_rm['Active_Trade'] = False # New column to track if a trade was taken
    df_rm['Capital_After_Trade'] = np.float64(initial_capital) # New column for capital after each trade

    # Ensure relevant date columns are datetime objects
    df_rm['Entry Date'] = pd.to_datetime(df_rm['Entry Date'])
    df_rm['Exit Date'] = pd.to_datetime(df_rm['Exit Date'])

    current_capital = initial_capital
    active_trade_exit_date = None # Tracks the exit date of an active trade

    for index, row in df_rm.iterrows():
        trade_entry_date = row['Entry Date']
        trade_exit_date = row['Exit Date']

        # Check if a trade is currently active and if the current trade's entry date is before or on the active trade's exit date
        if 1:
          if active_trade_exit_date is not None and trade_entry_date <= active_trade_exit_date:
              # Skip this trade as another is active or just exited on the same day
              df_rm.loc[index, 'Capital_At_Entry'] = current_capital
              df_rm.loc[index, 'Active_Trade'] = False
              df_rm.loc[index, 'Capital_After_Trade'] = current_capital
              continue

        # If no trade is active or active_trade_exit_date has passed
        df_rm.loc[index, 'Capital_At_Entry'] = current_capital
        df_rm.loc[index, 'Active_Trade'] = True

        # Calculate Risk Amount per Trade
        risk_amount_per_trade = current_capital * risk_percentage_per_trade
        df_rm.loc[index, 'Risk_Amount_Per_Trade'] = risk_amount_per_trade

        # Calculate Quantity
        price_difference = abs(row['Proximal'] - row['Distal'])
        if price_difference == 0:
            quantity = 0
        else:
            quantity = risk_amount_per_trade / price_difference
        df_rm.loc[index, 'Quantity'] = int(quantity) # Assuming whole units for simplicity

        # Calculate actual PnL for the trade
        #trade_pnl = row['R-Multiple'] * risk_amount_per_trade
        trade_pnl = row['P/L'] * int(quantity)
        df_rm.loc[index, 'Trade_PnL'] = trade_pnl

        # Update current capital after this trade
        current_capital += trade_pnl
        df_rm.loc[index, 'Capital_After_Trade'] = current_capital

        df_rm.loc[index, 'Zone_Type'] = 'Demand' if row['Target'] > row['Proximal'] else 'Supply'

        # Set the exit date for the newly active trade
        active_trade_exit_date = trade_exit_date
    df_rm = df_rm.drop(columns=['Entry Price','Exit Price','Outcome','P/L','R-Multiple','Proximal','Distal','Target'])

    return df_rm

