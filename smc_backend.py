# 4. REGIME CLASSIFICATION - adaptive percentile-rank thresholding
# --------------------------------------------------------------------------- #
def classify_regime(
    df: pd.DataFrame,
    rank_window: int = 52,
    bullish_pct: float = 0.70,
    bearish_pct: float = 0.30,
    smoothing_bars: int = 3,
) -> pd.DataFrame:
    """
    SNR_t = log_slope_t / log_ATR_t
          (fractional growth rate, scaled by the current noise floor)

    Instead of comparing SNR to a fixed constant, we compute its trailing
    percentile RANK over `rank_window` bars: "is today's SNR higher than
    X% of the last N bars' SNR?" This makes the Bullish/Bearish/Sideways
    cutoffs self-calibrating per ticker, per timeframe, and per volatility
    regime - it can never structurally fail to reach one side, because it
    is defined relative to the instrument's own recent behavior rather than
    an arbitrary absolute number.

    A short (default 3-bar) MEDIAN filter is applied to the rank series
    before thresholding. A median filter rejects single-bar noise spikes
    without averaging in old information the way a moving average would -
    it does not reintroduce the phase lag this whole approach exists to
    avoid.
    """
    snr = df["log_slope"] / df["log_atr"]
    df["SNR"] = snr

    def _rank_of_last(x: pd.Series) -> float:
        return (x.iloc[-1] > x).mean()

    rank = snr.rolling(rank_window, min_periods=max(20, rank_window // 3)).apply(
        _rank_of_last, raw=False
    )
    if smoothing_bars > 1:
        rank = rank.rolling(smoothing_bars, min_periods=1).median()
    df["rank"] = rank

    # Estimation certainty from the filter's own posterior slope variance -
    # tighter posterior (lower variance) => higher confidence in the reading.
    slope_std = np.sqrt(df["slope_var"])
    certainty = 1.0 / (1.0 + (slope_std / slope_std.median()))

    regimes, confidences = [], []
    for r, c in zip(rank, certainty):
        if pd.isna(r):
            # regimes.append("Insufficient Data")
            regimes.append(0)
            confidences.append(0.0)
            continue

        if r >= bullish_pct:
            # regime = "Bullish Trend"
            regime = 1
            strength = (r - bullish_pct) / (1.0 - bullish_pct)
        elif r <= bearish_pct:
            # regime = "Bearish Trend"
            regime = -1
            strength = (bearish_pct - r) / bearish_pct
        else:
            # regime = "Sideways / Mean-Reverting"
            regime = 0
            # strength here = how close to the CENTER of the neutral band (0.5)
            strength = 1.0 - abs(r - 0.5) / (bullish_pct - 0.5)

        confidence = 100.0 * float(np.clip(0.6 * strength + 0.4 * c, 0.0, 1.0))
        regimes.append(regime)
        confidences.append(round(confidence, 1))

    # df["regime"] = regimes
    df["Trend"] = regimes
    df["confidence_pct"] = confidences
    return df


