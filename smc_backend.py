# 2. VOLATILITY LAYER - True Range / ATR computed in LOG space
# --------------------------------------------------------------------------- #
def compute_log_atr(df: pd.DataFrame, window: int = 14) -> pd.Series:
    """
    Log-space Average True Range. Using log(High), log(Low), log(Close)
    puts the noise floor in the same units as the log-slope from the Kalman
    filter (fractional move per bar), so no further division by price level
    is required downstream - this is what makes the SNR calculation
    scale-invariant across a stock's entire price history.
    """
    log_h, log_l, log_c = np.log(df["High"]), np.log(df["Low"]), np.log(df["Close"])
    prev_log_c = log_c.shift(1)

    tr = pd.concat(
        [(log_h - log_l), (log_h - prev_log_c).abs(), (log_l - prev_log_c).abs()],
        axis=1,
    ).max(axis=1)

    return tr.ewm(alpha=1.0 / window, min_periods=window, adjust=False).mean()


# --------------------------------------------------------------------------- #
# 3. KALMAN FILTER - LOG-PRICE LOCAL LINEAR TREND MODEL
# --------------------------------------------------------------------------- #
@dataclass
class KalmanTrendFilter:
    """
    State vector:      x_t = [log_level_t, log_slope_t]^T
    log_slope_t is the instantaneous fractional growth rate per bar - e.g.
    0.02 means the filtered price is currently growing ~2% per bar. This is
    directly comparable across any price level or point in the stock's
    history, which a raw-price slope is not.

    Transition:  x_t = F x_{t-1} + w_t,  F = [[1, 1], [0, 1]]
    Observation: z_t = H x_t + v_t,      H = [1, 0]   (we observe log-price)
    """

    level_process_var_ratio: float = 1e-3
    slope_process_var_ratio: float = 1e-3
    # Both ratios are expressed relative to the empirical variance of
    # bar-to-bar log-returns, so the filter self-calibrates to each
    # instrument's own volatility rather than needing per-ticker retuning.

    def run(self, log_prices: np.ndarray) -> pd.DataFrame:
        n = len(log_prices)
        diffs = np.diff(log_prices)
        base_var = np.var(diffs) if len(diffs) > 1 and np.var(diffs) > 0 else 1e-6

        R = base_var
        Q = np.array(
            [
                [base_var * self.level_process_var_ratio, 0.0],
                [0.0, base_var * self.slope_process_var_ratio],
            ]
        )
        F = np.array([[1.0, 1.0], [0.0, 1.0]])
        H = np.array([[1.0, 0.0]])

        x = np.array([log_prices[0], 0.0])
        P = np.diag([base_var, base_var])

        log_levels = np.empty(n)
        log_slopes = np.empty(n)
        slope_vars = np.empty(n)

        for t in range(n):
            x_pred = F @ x
            P_pred = F @ P @ F.T + Q

            z = log_prices[t]
            y = z - (H @ x_pred)[0]
            S = (H @ P_pred @ H.T)[0, 0] + R
            K = (P_pred @ H.T).flatten() / S

            x = x_pred + K * y
            P = (np.eye(2) - np.outer(K, H)) @ P_pred

            log_levels[t], log_slopes[t] = x
            slope_vars[t] = P[1, 1]

        return pd.DataFrame(
            {
                "log_level": log_levels,
                "log_slope": log_slopes,
                "slope_var": slope_vars,
            }
        )


